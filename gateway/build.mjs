// Builds dist/quay-gateway.mjs (Node, Deno, Bun, containers) and dist/worker.mjs
// (Cloudflare Workers), and copies the core into cli/vendor/gateway so the CLI
// package carries it. `node gateway/build.mjs --check` fails when either is stale.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));
export const VENDOR = join(root, "..", "cli", "vendor", "gateway");
export const VENDORED = ["core.mjs", "page.mjs", "lru.mjs", "node.mjs"];
const BANNER =
  "// @quay/gateway. Generated by gateway/build.mjs from gateway/src. Do not edit.";

export const BUNDLES = {
  "quay-gateway.mjs": {
    entryPoints: [join(root, "src", "bin.mjs")],
    platform: "node",
    target: "node20",
    banner: { js: BANNER },
  },
  "worker.mjs": {
    entryPoints: [join(root, "src", "worker.mjs")],
    platform: "neutral",
    target: "es2022",
    banner: { js: BANNER },
  },
};

export async function bundle(name) {
  const esbuild = await import("esbuild");
  const result = await esbuild.build({
    ...BUNDLES[name],
    absWorkingDir: root,
    bundle: true,
    format: "esm",
    write: false,
    legalComments: "none",
    logLevel: "silent",
  });
  return result.outputFiles[0].text;
}

export function vendored(name) {
  return `${BANNER}\n${readFileSync(join(root, "src", name), "utf8")}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  const stale = [];
  const put = (path, text) => {
    let current = null;
    try {
      current = readFileSync(path, "utf8");
    } catch {}
    if (current === text) return;
    if (check) stale.push(path);
    else {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, text);
    }
  };
  for (const name of Object.keys(BUNDLES))
    put(join(root, "dist", name), await bundle(name));
  for (const name of VENDORED) put(join(VENDOR, name), vendored(name));
  if (stale.length) {
    console.error(`stale, run node gateway/build.mjs:\n${stale.join("\n")}`);
    process.exit(1);
  }
  for (const name of Object.keys(BUNDLES)) {
    const bytes = readFileSync(join(root, "dist", name)).length;
    console.log(`dist/${name} ${bytes} bytes`);
  }
  console.log(`cli/vendor/gateway ${VENDORED.join(", ")}`);
}
