// Builds dist/quay.js (browser bundle) and cli/vendor/relay/server.mjs (the Node relayer host,
// vendored so the packed CLI carries it). `node build.mjs --check` fails when the vendored file is stale.
import { mkdirSync, readFileSync, statSync, writeFileSync, existsSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";
import { build } from "esbuild";

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
export const VENDORED = here("../cli/vendor/relay/server.mjs");
const BANNER = "// Quay relayer host. Generated by client/build.mjs from client/src. Do not edit.";

export async function bundleRelay() {
  const result = await build({
    entryPoints: [here("./src/relay-server.mjs")],
    absWorkingDir: here("./"),
    bundle: true,
    write: false,
    format: "esm",
    platform: "node",
    target: "node20",
    external: ["near-api-js"],
    banner: { js: BANNER },
    legalComments: "none",
    logLevel: "silent",
  });
  return result.outputFiles[0].text;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--check")) {
    const fresh = await bundleRelay();
    if (!existsSync(VENDORED) || readFileSync(VENDORED, "utf8") !== fresh) {
      console.error("cli/vendor/relay/server.mjs is stale: run `node client/build.mjs`");
      process.exit(1);
    }
    console.log("cli/vendor/relay/server.mjs is up to date");
  } else {
    const out = here("./dist/quay.js");
    await build({
      entryPoints: [here("./src/index.mjs")],
      outfile: out,
      bundle: true,
      minify: true,
      format: "esm",
      target: "es2022",
      platform: "browser",
      // only the Node explicit-key path imports these, lazily; the browser never loads them
      external: ["near-api-js", "./failover.mjs"],
      legalComments: "none",
    });
    // fastdata.mjs (gas-only data) and extras.mjs (functions, checkout) are lazy siblings: dist/quay.js imports them by URL on demand.
    for (const name of ["fastdata", "extras"]) {
      const lazyOut = here(`./dist/${name}.mjs`);
      await build({ entryPoints: [here(`./src/${name}.mjs`)], outfile: lazyOut, bundle: true, minify: true, format: "esm", target: "es2022", platform: "browser", legalComments: "none" });
      console.log(`client/dist/${name}.mjs ${statSync(lazyOut).size} bytes, gzip ${gzipSync(readFileSync(lazyOut)).length} bytes (loaded on demand)`);
    }
    // The dashboard loads this lazily as assets/status.js (web/build.mjs copies it).
    const statusOut = here("./dist/status.js");
    await build({ entryPoints: [here("./src/status.mjs")], outfile: statusOut, bundle: true, minify: true, format: "esm", target: "es2022", platform: "browser", legalComments: "none" });
    console.log(`client/dist/status.js ${statSync(statusOut).size} bytes, gzip ${gzipSync(readFileSync(statusOut)).length} bytes`);
    const size = statSync(out).size;
    console.log(`client/dist/quay.js ${size} bytes (${(size / 1024).toFixed(1)} KB), gzip ${gzipSync(readFileSync(out)).length} bytes`);
    mkdirSync(dirname(VENDORED), { recursive: true });
    writeFileSync(VENDORED, await bundleRelay());
    console.log("wrote cli/vendor/relay/server.mjs");
  }
}
